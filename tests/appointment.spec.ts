import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    window.open = (url) => { document.documentElement.dataset.whatsapp = String(url); return null }
  })
})

test('two-step booking validates details, preserves choices and prepares a request', async ({ page }) => {
  await page.goto('/')
  await page.locator('.hero-pill').click()
  await expect(page).toHaveURL(/#appointment$/)
  const card = page.locator('.appointment-card')
  await expect(card.locator('.booking-steps li')).toHaveCount(2)
  await expect(page.getByLabel('Full name')).toBeVisible()
  await card.getByRole('button', { name: 'Continue choosing date' }).click()
  await expect(card.locator('.booking-calendar')).toHaveCount(0)
  await page.getByLabel('Full name').fill('Test Visitor')
  await page.getByLabel('Contact number').fill('123')
  await page.getByRole('combobox', { name: 'Service *', exact: true }).click()
  await page.getByRole('option', { name: 'Orthopaedic rehabilitation', exact: true }).click()
  await card.getByRole('checkbox').check()
  await card.getByRole('button', { name: 'Continue choosing date' }).click()
  await expect(card.getByRole('alert')).toHaveText('Please enter a valid contact number.')
  await page.getByLabel('Contact number').fill('9876543210')
  await page.getByLabel('Email (optional)').fill('test@example.com')
  await card.getByText('Add a note', { exact: false }).click()
  await page.getByLabel('A note for the clinic').fill('Please call to confirm.')
  await card.getByRole('button', { name: 'Continue choosing date' }).click()
  await card.getByRole('button', { name: 'Next month' }).click()
  await card.locator('.booking-calendar-days button:not(:disabled)').nth(2).click()
  const chosenDate = await card.locator('.booking-calendar-days [aria-pressed="true"]').getAttribute('data-date')
  await card.locator('.booking-time').filter({ hasText: '11:00 AM' }).click()
  await card.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByLabel('Full name')).toHaveValue('Test Visitor')
  await expect(page.locator('#appointment-service')).toContainText('Orthopaedic rehabilitation')
  await card.getByRole('button', { name: 'Continue choosing date' }).click()
  await expect(card.locator(`.booking-calendar-days [data-date="${chosenDate}"]`)).toHaveAttribute('aria-pressed', 'true')
  await card.getByRole('button', { name: 'Book appointment', exact: true }).click()
  const whatsapp = await page.locator('html').getAttribute('data-whatsapp')
  const message = new URL(whatsapp!).searchParams.get('text')!
  for (const value of ['Test Visitor', '9876543210', 'test@example.com', 'Orthopaedic rehabilitation', '11:00 AM', 'Please call to confirm.']) expect(message).toContain(value)
  await expect(card.getByRole('link', { name: 'Open email' })).toHaveCount(0)
  await expect(card.locator('.booking-review')).toHaveCount(0)
  await card.getByRole('button', { name: 'Back', exact: true }).click()
  await page.getByLabel('Full name').fill('Updated Visitor')
  await card.getByRole('button', { name: 'Continue choosing date' }).click()
  await card.getByRole('button', { name: 'Book appointment', exact: true }).click()
  expect(decodeURIComponent((await page.locator('html').getAttribute('data-whatsapp'))!)).toContain('Updated Visitor')
})

for (const width of [320, 390, 768, 1440]) {
  test(`booking steps fit at ${width}px and support flexible dates`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/#appointment')
    const card = page.locator('.appointment-card')
    const checkWidth = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await checkWidth()
    await page.getByLabel('Full name').fill('Test Visitor')
    await page.getByLabel('Contact number').fill('9876543210')
    await page.getByRole('combobox', { name: 'Service *', exact: true }).click()
    await page.getByRole('option', { name: 'Not sure yet / help me choose', exact: true }).click()
    await card.getByRole('button', { name: 'Continue choosing date' }).click()
    await expect(card.locator('.booking-calendar')).toHaveCount(0)
    await card.getByRole('checkbox').check()
    await card.getByRole('button', { name: 'Continue choosing date' }).click()
    await checkWidth()
    await expect(card.getByRole('button', { name: 'Flexible date' })).toHaveAttribute('aria-pressed', 'true')
    await card.getByRole('button', { name: 'Afternoon', exact: true }).click()
    await expect(card.getByRole('radio', { name: '09:00 AM', exact: true })).toHaveCount(0)
    await card.locator('.booking-time').filter({ hasText: '12:00 PM' }).click()
    await card.getByRole('button', { name: 'Evening', exact: true }).click()
    await expect(card.getByRole('radio', { name: 'Any time works for me' })).toBeChecked()
    await expect(card.getByRole('radio', { name: '12:00 PM', exact: true })).toHaveCount(0)
    await expect(card.getByRole('radio', { name: '06:00 PM', exact: true })).toHaveCount(1)
    await card.getByRole('button', { name: 'Morning', exact: true }).click()
    await expect(card.getByRole('radio', { name: '09:00 AM', exact: true })).toHaveCount(1)
    await expect(card.getByRole('button', { name: 'Previous month' })).toBeDisabled()
    const today = await card.locator('[aria-current="date"]').getAttribute('data-date')
    for (const day of await card.locator('.booking-calendar-days button').all()) {
      if ((await day.getAttribute('data-date'))! < today!) await expect(day).toBeDisabled()
    }
    await card.getByRole('button', { name: 'Next month' }).click()
    await expect(card.getByRole('button', { name: 'Next month' })).toBeDisabled()
    const currentDate = new Date(`${today}T12:00:00`)
    const lastAllowed = new Date(currentDate.getFullYear(), currentDate.getMonth() + 2, 0)
    for (const day of await card.locator('.booking-calendar-days button').all()) {
      const value = await day.getAttribute('data-date')
      if (new Date(`${value}T00:00:00`) > lastAllowed) await expect(day).toBeDisabled()
    }
    await card.getByRole('button', { name: 'Previous month' }).click()
    await expect(card.locator('[aria-current="date"]')).toHaveAttribute('data-date', today!)
    await card.locator('[aria-current="date"]').click()
    await card.getByRole('button', { name: 'Flexible date' }).click()
    await card.getByRole('button', { name: 'Book appointment', exact: true }).click()
    await checkWidth()
    await expect(card.locator('.booking-review')).toHaveCount(0)
    const request = decodeURIComponent((await page.locator('html').getAttribute('data-whatsapp'))!)
    expect(request).toContain('Flexible')
    expect(request).toContain('Not sure yet')
  })
}

