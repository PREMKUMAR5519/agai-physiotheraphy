test('service dropdown supports keyboard navigation and dismissal', async ({ page }) => {
  await page.goto('/#appointment')
  const select = page.getByRole('combobox', { name: 'Service *', exact: true })
  await select.focus()
  await select.press('ArrowDown')
  await expect(select).toHaveAttribute('aria-expanded', 'true')
  await select.press('End')
  await select.press('Enter')
  await expect(select).toContainText('Not sure yet / help me choose')
  await expect(select).toHaveAttribute('aria-expanded', 'false')
  await select.press('ArrowDown')
  await select.press('Home')
  await select.press('ArrowDown')
  await select.press('Enter')
  await expect(select).toContainText('Strength & conditioning')
  await select.click()
  await select.press('Escape')
  await expect(select).toHaveAttribute('aria-expanded', 'false')
  await select.click()
  await page.getByLabel('Full name').click()
  await expect(select).toHaveAttribute('aria-expanded', 'false')
  await select.focus()
  await select.press('p')
  await select.press('Enter')
  await expect(select).toContainText('Pelvic floor rehabilitation')
  await select.click()
  await select.press('Tab')
  await expect(select).toHaveAttribute('aria-expanded', 'false')
})
